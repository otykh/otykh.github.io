// Pre-renders a title in a given font as braille, at a few heights, using headless Chrome to draw
// the text. Writes a script defining one global with the frames, next to index.html.
// usage: node tools/title.mjs "<text>" "<font>" <out file> <global name> <rows,rows,...> [--preview]
// A size can cap its width as rows:cols (e.g. 4:30), squeezing the letters slightly to fit. Text with
// '|' is drawn as stacked lines ("The|Dot"), each that many rows tall, a blank row between.
import { spawn } from 'child_process';
import fs from 'fs';

const [text, font, out, name, sizes] = process.argv.slice(2);
const preview = process.argv.includes('--preview');
const sizeList = sizes.split(',').map(s => s.split(':').map(Number));
const rowsList = sizeList.map(s => s[0]);

const chrome = spawn('/Applications/Google Chrome.app/Contents/MacOS/Google Chrome',
  ['--headless=new', '--remote-debugging-port=9339', `--user-data-dir=${fs.mkdtempSync('/tmp/title-')}`, 'about:blank'], { stdio: 'ignore' });
const sleep = ms => new Promise(r => setTimeout(r, ms));
await sleep(1500);
const ws = new WebSocket((await (await fetch('http://127.0.0.1:9339/json')).json()).find(t => t.type === 'page').webSocketDebuggerUrl);
await new Promise(r => ws.onopen = r);
let id = 0;
const pending = {};
ws.onmessage = e => { const m = JSON.parse(e.data); if (pending[m.id]) { pending[m.id](m); delete pending[m.id]; } };
const send = (method, params) => new Promise(r => { pending[++id] = r; ws.send(JSON.stringify({ id, method, params })); });

// In the page: draw the text large, crop to its ink, and for each size sample the coverage of each
// braille dot's area; a dot is on when at least 30% of its area is ink, which keeps thin strokes.
const exprFor = text => `(() => {
  const S = 400, c = document.createElement('canvas'), g = c.getContext('2d');
  g.font = ${JSON.stringify(`${400}px '${font}'`)};
  c.width = Math.ceil(g.measureText(${JSON.stringify(text)}).width) + 40; c.height = S * 1.4;
  g.font = ${JSON.stringify(`${400}px '${font}'`)}; g.textBaseline = 'middle'; g.fillText(${JSON.stringify(text)}, 20, c.height / 2);
  const d = g.getImageData(0, 0, c.width, c.height).data;
  let x0 = c.width, x1 = 0, y0 = c.height, y1 = 0;
  for (let y = 0; y < c.height; y++) for (let x = 0; x < c.width; x++) if (d[(y * c.width + x) * 4 + 3] > 128) {
    x0 = Math.min(x0, x); x1 = Math.max(x1, x); y0 = Math.min(y0, y); y1 = Math.max(y1, y);
  }
  const iw = x1 - x0 + 1, ih = y1 - y0 + 1, B = [[1, 8], [2, 16], [4, 32], [64, 128]];
  return JSON.stringify(${JSON.stringify(sizeList)}.map(([rows, most]) => {
    const H = rows * 4, cols = Math.min(most || Infinity, Math.ceil(H * iw / ih / 2)), W = cols * 2, sx = iw / W, sy = ih / H;
    const lines = [];
    for (let r = 0; r < rows; r++) {
      let line = '';
      for (let col = 0; col < cols; col++) {
        let bits = 0;
        for (let dy = 0; dy < 4; dy++) for (let dx = 0; dx < 2; dx++) {
          const X = col * 2 + dx, Y = r * 4 + dy; let ink = 0, n = 0;
          for (let y = Math.floor(y0 + Y * sy); y < y0 + (Y + 1) * sy; y++) for (let x = Math.floor(x0 + X * sx); x < x0 + (X + 1) * sx; x++) { n++; if (d[(y * c.width + x) * 4 + 3] > 128) ink++; }
          if (ink / n >= 0.3) bits |= B[dy][dx];
        }
        line += String.fromCharCode(0x2800 + bits);
      }
      lines.push(line);
    }
    return { cols, rows, lines };
  }));
})()`;
await send('Page.navigate', { url: 'data:text/html,<body>' });
await sleep(500);
const parts = [];
for (const part of text.split('|')) parts.push(JSON.parse((await send('Runtime.evaluate', { expression: exprFor(part), returnByValue: true })).result.result.value));
// Stack the parts of each size, left aligned and padded to the widest.
const art = parts[0].map((_, k) => {
  const pieces = parts.map(p => p[k]), cols = Math.max(...pieces.map(p => p.cols)), blank = '\u2800'.repeat(cols);
  const lines = pieces.flatMap((p, i) => [...(i ? [blank] : []), ...p.lines.map(l => l + '\u2800'.repeat(cols - p.cols))]);
  return { cols, rows: lines.length, lines };
});
ws.close();
chrome.kill();

if (preview) {
  for (const a of art) console.log(`${a.cols}x${a.rows}\n` + a.lines.join('\n').replace(/⠀/g, ' '));
} else {
  fs.writeFileSync(out, `// Generated by tools/title.mjs: "${text}" in ${font}, as braille at ${rowsList.join(', ')} rows tall.\nconst ${name} = ${JSON.stringify(art)};\n`);
  console.log('wrote', out);
}
