// Pre-renders the Star of Life (three bars at 60° with the Rod of Asclepius cut out) turning on
// its vertical axis, as braille frames. Writes eso-star.js next to index.html.
// usage: node tools/star.mjs [cols rows frames] [--preview i,j,...]
import fs from 'fs';

const args = process.argv.slice(2);
const preview = args.includes('--preview') ? args[args.indexOf('--preview') + 1].split(',').map(Number) : null;
const [COLS, ROWS, FRAMES] = args.filter(a => /^\d+$/.test(a)).map(Number).concat([16, 8, 48]).slice(0, 3);
const W = COLS * 2, H = ROWS * 4;     // frame size in dots
const R = Math.min(W, H) / 2 - 0.5;   // star radius in dots
const BAR = 0.27;                     // bar half-width, × R
const THICK = 0.08;                   // half thickness of the star, × R
const SS = 4;                         // samples per dot along each axis

// Shape in unit coordinates (radius 1, y down).
const inStar = (x, y) => [0, Math.PI / 3, 2 * Math.PI / 3].some(a => {
  const u = x * Math.cos(a) + y * Math.sin(a), v = -x * Math.sin(a) + y * Math.cos(a);
  return Math.abs(u) <= BAR && Math.abs(v) <= 1;
});
const inStaff = (x, y) => Math.abs(x) < 0.07 && Math.abs(y) < 0.78;
const inSnake = (x, y) => y > -0.62 && y < 0.62 && Math.abs(x - 0.2 * Math.sin(y * 9 + 0.8) * (1 - Math.abs(y) / 1.4)) < 0.07;
const inRod = (x, y) => inStaff(x, y) || inSnake(x, y);

const DOT_BIT = [[0x01, 0x08], [0x02, 0x10], [0x04, 0x20], [0x40, 0x80]];
const frames = [];
for (let f = 0; f < FRAMES; f++) {
  const a = f / FRAMES * 2 * Math.PI, c = Math.cos(a), s = Math.sin(a);
  const on = new Uint8Array(W * H), cut = new Uint8Array(W * H);
  const plot = (buf, x, y, z) => {
    const X = Math.round(W / 2 - 0.5 + (x * c + z * s) * R), Y = Math.round(H / 2 - 0.5 + y * R);
    if (X >= 0 && Y >= 0 && X < W && Y < H) buf[Y * W + X] = 1;
  };
  const step = 1 / (R * SS);
  const face = (c >= 0 ? 1 : -1) * THICK;
  for (let y = -1; y <= 1; y += step) {
    for (let x = -1; x <= 1; x += step) {
      if (!inStar(x, y)) continue;
      for (let z = -THICK; z <= THICK; z += step) plot(on, x, y, z);
      if (inRod(x, y)) plot(cut, x, y, face);
    }
  }
  const rows = [];
  for (let r = 0; r < ROWS; r++) {
    let line = '';
    for (let col = 0; col < COLS; col++) {
      let bits = 0;
      for (let dy = 0; dy < 4; dy++) for (let dx = 0; dx < 2; dx++) {
        const i = (r * 4 + dy) * W + col * 2 + dx;
        if (on[i] && !cut[i]) bits |= DOT_BIT[dy][dx];
      }
      line += String.fromCharCode(0x2800 + bits);
    }
    rows.push(line);
  }
  frames.push(rows);
}

if (preview) {
  for (const i of preview) console.log(`frame ${i}\n` + frames[i].join('\n').replace(/⠀/g, ' '));
} else {
  const out = `// Generated by tools/star.mjs: the Star of Life turning on its vertical axis, ${FRAMES} braille frames.\n` +
    `const ESO_STAR = ${JSON.stringify({ cols: COLS, rows: ROWS, frames })};\n`;
  fs.writeFileSync(new URL('../eso-star.js', import.meta.url), out);
  console.log('wrote eso-star.js', out.length, 'bytes');
}
